def pool_df():
    """返回去重后的股票池 DataFrame。"""
    import pandas as pd

    rows = []
    seen = {}
    for (code, name, cat, sub, mode, e, a, h, lvl, cap, cyc) in POOL:
        if code in seen:
            continue  # 去重：同一代码只保留首次出现
        seen[code] = True
        rows.append(
            {
                "code": code,
                "name": name,
                "cat": cat,
                "sub": sub,
                "dps_mode": mode,
                "entry": e,
                "add": a,
                "heavy": h,
                "level": lvl,
                "cap": cap,
                "need_cycle": cyc,
                "in_book": code in BOOK_CODES,
            }
        )
    return pd.DataFrame(rows)


